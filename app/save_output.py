import orjson
from datetime import datetime, timezone
from pathlib import Path
from app.validate_input import AgentState

OUTPUT_DIR = Path("outputs")

def save_output(state: AgentState) -> AgentState:
    from app.logger import setup_logger, log_state, NodeTimer
    incident_number = (state.get("extracted_facts") or {}).get("incident_number", "UNKNOWN")
    logger = setup_logger(incident_number)
    log_state(logger, "save_output", "in", state)

    final = state.get("final_response")
    facts = state.get("extracted_facts", {})
    incident_number = facts.get("incident_number", "UNKNOWN")

    if not final:
        print(f"[save_output] ❌ No final response to save")
        return state

    output = {
        "incident_number": incident_number,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "confidence_score": state.get("confidence_score", 0.0),
        "cost_estimate": state.get("cost_estimate", 0.0),
        "validation_warnings": state.get("validation_warnings", []),
        "extracted_facts": facts,
        "final_response": final
    }

    # Save JSON
    json_path = OUTPUT_DIR / f"{incident_number}_insight.json"
    json_path.write_bytes(orjson.dumps(output, option=orjson.OPT_INDENT_2))
    print(f"[save_output] 💾 Saved JSON: {json_path}")

    # Save pretty Markdown
    fr = final if isinstance(final, dict) else {}
    priority = facts.get("priority", "Unknown")
    duration = facts.get("outage_duration_minutes")
    duration_str = f"{duration} minutes" if duration else "Unknown"

    # Risk level color indicator
    risk = fr.get("risk_level", "Unknown")
    risk_icon = {"Critical": "🔴", "High": "🟠", "Medium": "🟡", "Low": "🟢"}.get(risk, "⚪")

    # Confidence bar
    confidence = state.get("confidence_score", 0.0)
    filled = int(confidence * 10)
    confidence_bar = "█" * filled + "░" * (10 - filled)

    md_lines = [
        f"# 🔍 RCA Report — {incident_number}",
        f"",
        f"> Generated: {output['generated_at']}",
        f"",
        f"---",
        f"",
        f"## 📋 Incident Overview",
        f"",
        f"| Field | Value |",
        f"|---|---|",
        f"| **Incident** | {incident_number} |",
        f"| **Priority** | {priority} |",
        f"| **Risk Level** | {risk_icon} {risk} |",
        f"| **Outage Duration** | {duration_str} |",
        f"| **Impacted Services** | {', '.join(facts.get('impacted_services', [])) or 'Unknown'} |",
        f"| **CI Name** | {facts.get('ci_name', 'Unknown')} |",
        f"| **Assignment Group** | {facts.get('assignment_group', 'Unknown')} |",
        f"| **Linked Problem** | {'✅ Yes' if facts.get('has_problem_record') else '❌ No'} |",
        f"| **Linked Change** | {'✅ Yes' if facts.get('has_change_record') else '❌ No'} |",
        f"",
        f"---",
        f"",
        f"## 🎯 Confidence Score",
        f"",
        f"`[{confidence_bar}]` {int(confidence * 100)}%",
        f"",
        f"---",
        f"",
        f"## 📝 Incident Summary",
        f"",
        f"{fr.get('incident_summary', 'Not available')}",
        f"",
        f"---",
        f"",
        f"## 🔎 Root Cause Analysis",
        f"",
        f"{fr.get('root_cause_analysis', 'Not available')}",
        f"",
        f"---",
        f"",
        f"## 🛡️ Prevention Measures",
        f"",
    ]

    for item in fr.get("prevention_measures", []):
        md_lines.append(f"- {item}")

    md_lines += [
        f"",
        f"---",
        f"",
        f"## ✅ Resolution Recommendations",
        f"",
    ]
    for item in fr.get("resolution_recommendations", []):
        md_lines.append(f"- {item}")

    md_lines += [
        f"",
        f"---",
        f"",
        f"## 🤖 Automation & Monitoring Suggestions",
        f"",
    ]
    for item in fr.get("automation_monitoring_suggestions", []):
        md_lines.append(f"- {item}")

    md_lines += [
        f"",
        f"---",
        f"",
        f"## 🔬 Evidence Used",
        f"",
    ]
    for item in fr.get("evidence_used", []):
        md_lines.append(f"- {item}")

    md_lines += [
        f"",
        f"---",
        f"",
        f"## ⚠️ Missing Information",
        f"",
    ]
    missing = fr.get("missing_information", [])
    if missing:
        for item in missing:
            md_lines.append(f"- {item}")
    else:
        md_lines.append("- None — all key data was present")

    md_lines += [
        f"",
        f"---",
        f"",
        f"## 🔍 Error Keywords Detected",
        f"",
        f"`{'`, `'.join(facts.get('error_keywords', [])) or 'None detected'}`",
        f"",
        f"---",
        f"",
        f"*Report generated by ServiceNow AI Insight Agent*",
    ]

    md_path = OUTPUT_DIR / f"{incident_number}_insight.md"
    md_path.write_text("\n".join(md_lines), encoding="utf-8")
    print(f"[save_output] 📝 Saved Markdown: {md_path}")

    # Generate executive summary for P1/P2
    priority = facts.get("priority", "")
    if priority in ["P1", "P2"]:
        try:
            from app.executive_summary import generate_executive_summary
            print(f"[save_output] 📊 Generating executive summary...")
            exec_summary = generate_executive_summary(fr, facts)

            exec_md = OUTPUT_DIR / f"{incident_number}_executive_summary.md"
            exec_lines = [
                f"# 📊 Executive Summary — {incident_number}",
                f"",
                f"> For leadership review | Generated: {output['generated_at']}",
                f"",
                f"---",
                f"",
                f"| | |",
                f"|---|---|",
                f"| **What Happened** | {exec_summary.get('what_happened', 'N/A')} |",
                f"| **Business Impact** | {exec_summary.get('business_impact', 'N/A')} |",
                f"| **Likely Cause** | {exec_summary.get('likely_cause', 'N/A')} |",
                f"| **What We Did** | {exec_summary.get('what_we_did', 'N/A')} |",
                f"| **Next Steps** | {exec_summary.get('next_steps', 'N/A')} |",
                f"| **Automation Opportunity** | {exec_summary.get('automation_opportunity', 'N/A')} |",
                f"",
                f"---",
                f"*Generated by ServiceNow AI Insight Agent*"
            ]
            exec_md.write_text("\n".join(exec_lines), encoding="utf-8")
            print(f"[save_output] 📊 Saved Executive Summary: {exec_md}")
        except Exception as e:
            print(f"[save_output] ⚠️  Could not generate executive summary: {e}")

        log_state(logger, "save_output", "out", state)

    return state